"use client";

import type { ReactNode } from "react";
import {
  ReportBody,
  ReportCover,
  ReportDataCard,
  ReportDelta,
  ReportDocument,
  ReportEmptyState,
  ReportExecutiveSummary,
  ReportFooter,
  ReportMetaGrid,
  ReportMetricCard,
  ReportMetricGrid,
  ReportPrintActions,
  ReportSection,
  ReportShell,
  ReportTable,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/reports";
import { clientTechnologyProfilePath } from "@/lib/clients/paths";
import { formatDisplayDate } from "@/lib/display";
import type { ProgressReportData } from "@/lib/reports/progress/types";
import { getScoreTextColorClass } from "@/lib/scoring/score-display";
import { BACK_TO_CLIENT_WORKSPACE_OVERVIEW } from "@/lib/technology-maturity/labels";
import { BRAND } from "@/lib/branding";
import { getReportTypeMeta } from "@/lib/reports/meta";
import { cn } from "@/lib/utils";

type ProgressReportPreviewProps = {
  clientId: string;
  data: ProgressReportData;
  /** Customer portal charcoal/phosphor presentation (SS-UX-010). Staff keeps document chrome. */
  isCustomerView?: boolean;
};

function CustomerProgressCover({
  title,
  subtitle,
}: {
  title: string;
  subtitle: string;
}) {
  return (
    <header className="customer-progress-report-cover border-b border-border px-6 py-8 sm:px-8 sm:py-10">
      <p className="text-xs font-semibold uppercase tracking-[0.2em] text-primary">
        Generated by {BRAND.productName}
      </p>
      <h3 className="mt-2 text-3xl font-bold tracking-tight text-foreground">{title}</h3>
      <p className="mt-3 max-w-3xl text-sm leading-relaxed text-muted-foreground">{subtitle}</p>
    </header>
  );
}

function CustomerMetricCard({
  label,
  value,
  valueClassName,
}: {
  label: string;
  value: ReactNode;
  valueClassName?: string;
}) {
  return (
    <div className="customer-progress-metric-card flex h-full flex-col rounded-sm border border-border bg-card p-4">
      <p className="text-xs font-semibold uppercase tracking-wide text-muted-foreground">{label}</p>
      <div className={cn("mt-2 text-3xl font-semibold tabular-nums text-foreground", valueClassName)}>
        {value}
      </div>
    </div>
  );
}

export function ProgressReportPreview({
  clientId,
  data,
  isCustomerView = false,
}: ProgressReportPreviewProps) {
  const meta = getReportTypeMeta("technology_progress");
  const coverTitle = meta.title;
  const coverSubtitle = meta.subtitle;

  if (isCustomerView) {
    return (
      <ReportShell className="customer-progress-report">
        <ReportPrintActions
          clientName={data.clientName}
          title="Technology Progress Report"
          description={data.reportPeriodLabel}
          backHref={clientTechnologyProfilePath(clientId)}
          backLabel={BACK_TO_CLIENT_WORKSPACE_OVERVIEW}
        />

        <ReportDocument className="customer-progress-report-document border-border bg-card shadow-none">
          <CustomerProgressCover title={coverTitle} subtitle={coverSubtitle} />

          <ReportBody className="space-y-8 px-6 py-8 sm:px-8">
            <div className="grid gap-4 border-b border-border pb-6 sm:grid-cols-2 lg:grid-cols-4">
              {[
                { label: "Client", value: data.clientName },
                { label: "Reporting Period", value: data.reportPeriodLabel },
                { label: "Generated", value: data.generatedDateLabel },
                {
                  label: "Current StackScore",
                  value: data.currentStackScore ?? "—",
                  emphasis: true,
                  valueClassName: getScoreTextColorClass(data.currentStackScore),
                },
              ].map((item) => (
                <div key={item.label}>
                  <p className="text-xs font-semibold uppercase tracking-wide text-muted-foreground">
                    {item.label}
                  </p>
                  <div
                    className={cn(
                      "mt-1 font-semibold text-foreground",
                      item.emphasis && "text-2xl font-bold",
                      item.valueClassName,
                    )}
                  >
                    {item.value}
                  </div>
                </div>
              ))}
            </div>

            <ReportSection title="Executive Summary" variant="accent">
              <ReportExecutiveSummary value={data.executiveSummary} />
            </ReportSection>

            <ReportSection
              title="Technology Maturity Movement"
              subtitle={
                data.lastAssessmentName
                  ? `Baseline from ${data.lastAssessmentName}${
                      data.lastAssessedAt ? ` · ${formatDisplayDate(data.lastAssessedAt)}` : ""
                    }`
                  : undefined
              }
              variant="accent"
            >
              <div className="grid auto-rows-fr grid-cols-1 gap-4 sm:grid-cols-2 xl:grid-cols-4">
                <CustomerMetricCard
                  label="Previous StackScore"
                  value={data.previousStackScore ?? "—"}
                />
                <CustomerMetricCard
                  label="Current StackScore"
                  value={data.currentStackScore ?? "—"}
                  valueClassName={getScoreTextColorClass(data.currentStackScore)}
                />
                <CustomerMetricCard
                  label="Change"
                  value={<ReportDelta value={data.scoreChange} />}
                />
                <CustomerMetricCard
                  label="Active Projects"
                  value={String(data.activeProjectCount)}
                />
              </div>
              {data.currentMaturityLabel ? (
                <p className="mt-4 text-sm text-muted-foreground">
                  Current maturity tier:{" "}
                  <strong className="text-foreground">{data.currentMaturityLabel}</strong>
                </p>
              ) : null}
            </ReportSection>

            <ReportSection title="Category Movement" variant="accent">
              {data.categoryChanges.length === 0 ? (
                <ReportEmptyState>No category score history is available yet.</ReportEmptyState>
              ) : (
                <ReportTable>
                  <TableHeader>
                    <TableRow>
                      <TableHead>Category</TableHead>
                      <TableHead>Previous</TableHead>
                      <TableHead>Current</TableHead>
                      <TableHead>Change</TableHead>
                    </TableRow>
                  </TableHeader>
                  <TableBody>
                    {data.categoryChanges.map((row) => (
                      <TableRow key={row.categoryName}>
                        <TableCell>{row.categoryName}</TableCell>
                        <TableCell>{row.previousScore ?? "—"}</TableCell>
                        <TableCell>{row.currentScore ?? "—"}</TableCell>
                        <TableCell>
                          <ReportDelta value={row.change} />
                        </TableCell>
                      </TableRow>
                    ))}
                  </TableBody>
                </ReportTable>
              )}
            </ReportSection>

            <ReportSection title="Completed Work" variant="accent">
              {data.completedProjectsSinceAssessment.length === 0 ? (
                <ReportEmptyState>
                  No completed projects were recorded during this reporting period.
                </ReportEmptyState>
              ) : (
                <div className="space-y-3">
                  {data.completedProjectsSinceAssessment.map((project) => (
                    <ReportDataCard
                      key={project.id}
                      title={project.title}
                      description={project.recommendationTitle ?? undefined}
                      aside={
                        project.completedAt ? formatDisplayDate(project.completedAt) : undefined
                      }
                      meta={
                        <div className="flex flex-wrap gap-3 text-muted-foreground">
                          {project.estimatedImpactPoints !== null ? (
                            <span>Expected: +{project.estimatedImpactPoints} pts</span>
                          ) : null}
                          {project.actualImpactPoints !== null ? (
                            <span className="font-medium text-foreground">
                              Actual: +{project.actualImpactPoints} pts
                            </span>
                          ) : null}
                        </div>
                      }
                    />
                  ))}
                </div>
              )}
            </ReportSection>

            <ReportSection title="Recommended Next Steps" variant="accent">
              <ul className="space-y-2 text-sm leading-relaxed text-foreground/90">
                {data.nextSteps.map((step) => (
                  <li key={step} className="flex gap-2">
                    <span className="text-primary" aria-hidden>
                      •
                    </span>
                    <span>{step}</span>
                  </li>
                ))}
              </ul>
              <p className="mt-4 text-sm text-muted-foreground">
                Journey phase: <strong className="text-foreground">{data.journeyPhaseLabel}</strong> ·{" "}
                {data.openRecommendationsCount} open recommendation
                {data.openRecommendationsCount === 1 ? "" : "s"}
              </p>
            </ReportSection>

            <ReportFooter confidentialFor={data.clientName} />
          </ReportBody>
        </ReportDocument>
      </ReportShell>
    );
  }

  return (
    <ReportShell>
      <ReportPrintActions
        clientName={data.clientName}
        title="Technology Progress Report"
        description={data.reportPeriodLabel}
        backHref={clientTechnologyProfilePath(clientId)}
        backLabel={BACK_TO_CLIENT_WORKSPACE_OVERVIEW}
      />

      <ReportDocument>
        <ReportCover reportType="technology_progress" />

        <ReportBody>
          <ReportMetaGrid
            items={[
              { label: "Client", value: data.clientName },
              { label: "Reporting Period", value: data.reportPeriodLabel },
              { label: "Generated", value: data.generatedDateLabel },
              {
                label: "Current StackScore",
                value: data.currentStackScore ?? "—",
                emphasis: true,
                valueClassName: getScoreTextColorClass(data.currentStackScore),
              },
            ]}
          />

          <ReportSection title="Executive Summary">
            <ReportExecutiveSummary value={data.executiveSummary} />
          </ReportSection>

          <ReportSection
            title="Technology Maturity Movement"
            subtitle={
              data.lastAssessmentName
                ? `Baseline from ${data.lastAssessmentName}${
                    data.lastAssessedAt ? ` · ${formatDisplayDate(data.lastAssessedAt)}` : ""
                  }`
                : undefined
            }
          >
            <ReportMetricGrid>
              <ReportMetricCard label="Previous StackScore" value={data.previousStackScore ?? "—"} />
              <ReportMetricCard
                label="Current StackScore"
                value={data.currentStackScore ?? "—"}
                valueClassName={getScoreTextColorClass(data.currentStackScore)}
              />
              <ReportMetricCard label="Change" value={<ReportDelta value={data.scoreChange} />} />
              <ReportMetricCard
                label="Active Projects"
                value={String(data.activeProjectCount)}
              />
            </ReportMetricGrid>
            {data.currentMaturityLabel ? (
              <p className="mt-4 text-sm text-muted-foreground">
                Current maturity tier: <strong>{data.currentMaturityLabel}</strong>
              </p>
            ) : null}
          </ReportSection>

          <ReportSection title="Category Movement">
            {data.categoryChanges.length === 0 ? (
              <ReportEmptyState>No category score history is available yet.</ReportEmptyState>
            ) : (
              <ReportTable>
                <TableHeader>
                  <TableRow>
                    <TableHead>Category</TableHead>
                    <TableHead>Previous</TableHead>
                    <TableHead>Current</TableHead>
                    <TableHead>Change</TableHead>
                  </TableRow>
                </TableHeader>
                <TableBody>
                  {data.categoryChanges.map((row) => (
                    <TableRow key={row.categoryName}>
                      <TableCell>{row.categoryName}</TableCell>
                      <TableCell>{row.previousScore ?? "—"}</TableCell>
                      <TableCell>{row.currentScore ?? "—"}</TableCell>
                      <TableCell>
                        <ReportDelta value={row.change} />
                      </TableCell>
                    </TableRow>
                  ))}
                </TableBody>
              </ReportTable>
            )}
          </ReportSection>

          <ReportSection title="Completed Work">
            {data.completedProjectsSinceAssessment.length === 0 ? (
              <ReportEmptyState>
                No completed projects were recorded during this reporting period.
              </ReportEmptyState>
            ) : (
              <div className="space-y-3">
                {data.completedProjectsSinceAssessment.map((project) => (
                  <ReportDataCard
                    key={project.id}
                    title={project.title}
                    description={project.recommendationTitle ?? undefined}
                    aside={
                      project.completedAt ? formatDisplayDate(project.completedAt) : undefined
                    }
                    meta={
                      <div className="flex flex-wrap gap-3">
                        {project.estimatedImpactPoints !== null ? (
                          <span>Expected: +{project.estimatedImpactPoints} pts</span>
                        ) : null}
                        {project.actualImpactPoints !== null ? (
                          <span className="font-medium text-foreground">
                            Actual: +{project.actualImpactPoints} pts
                          </span>
                        ) : null}
                      </div>
                    }
                  />
                ))}
              </div>
            )}
          </ReportSection>

          <ReportSection title="Recommended Next Steps">
            <ul className="space-y-2 text-sm leading-relaxed text-muted-foreground">
              {data.nextSteps.map((step) => (
                <li key={step} className="flex gap-2">
                  <span className="text-primary">•</span>
                  <span>{step}</span>
                </li>
              ))}
            </ul>
            <p className="mt-4 text-sm text-muted-foreground">
              Journey phase: <strong>{data.journeyPhaseLabel}</strong> ·{" "}
              {data.openRecommendationsCount} open recommendation
              {data.openRecommendationsCount === 1 ? "" : "s"}
            </p>
          </ReportSection>

          <ReportFooter confidentialFor={data.clientName} />
        </ReportBody>
      </ReportDocument>
    </ReportShell>
  );
}
